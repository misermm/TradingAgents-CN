def create_charlie_munger_analyst(llm, toolkit):
    return create_master_analyst(
        master_id="charlie_munger",
        llm=llm,
        toolkit=toolkit,
        philosophy=CHARLIE_MUNGER_PHILOSOPHY,
        framework=CHARLIE_MUNGER_FRAMEWORK,
        output_format=CHARLIE_MUNGER_OUTPUT,
        tools_list=[toolkit.get_stock_fundamentals_unified],
    )
