def create_michael_burry_analyst(llm, toolkit):
    return create_master_analyst(
        master_id="michael_burry",
        llm=llm,
        toolkit=toolkit,
        philosophy=MICHAEL_BURRY_PHILOSOPHY,
        framework=MICHAEL_BURRY_FRAMEWORK,
        output_format=MICHAEL_BURRY_OUTPUT,
        tools_list=[toolkit.get_stock_fundamentals_unified],
    )
